"""Serve the FLUX.2 [dev] LoRA trained by otterimage/train_flux2_lora.py.

Loads the base weights and the LoRA from the `otterimage-flux2-finetune`
Volume (the same one the golden-demos outpost mounts at /model while
training) and exposes a Gradio UI.

    modal serve otterimage/serve_flux2_lora.py    # temporary URL, hot reload
    modal deploy otterimage/serve_flux2_lora.py   # persistent, scales to zero

The bf16 transformer (~64 GB) plus VAE fit on one H100 because the text
encoder stays out of the container: the pipeline is built with
`text_encoder=None` and fed embeddings from Hugging Face's remote encoder.
"""

from dataclasses import dataclass
from pathlib import Path

import modal

app = modal.App(name="otterimage-flux2-lora")

MODEL_DIR = "/model"
LORA_DIR = f"{MODEL_DIR}/lora"
volume = modal.Volume.from_name("otterimage-flux2-finetune", create_if_missing=True)

huggingface_secret = modal.Secret.from_name("huggingface-secret", required_keys=["HF_TOKEN"])

image = (
    modal.Image.debian_slim(python_version="3.12")
    .apt_install("git")
    .uv_pip_install(requirements=[str(Path(__file__).parent / "requirements.txt")])
    .uv_pip_install("gradio==5.49.1", "fastapi[standard]==0.116.2", "pydantic==2.11.9")
    .env({"HF_XET_HIGH_PERFORMANCE": "1"})
)

REMOTE_TEXT_ENCODER_URL = "https://remote-text-encoder-flux-2.huggingface.co/predict"


def remote_text_encode(prompt: str):
    import io
    import os

    import requests
    import torch

    response = requests.post(
        REMOTE_TEXT_ENCODER_URL,
        json={"prompt": prompt},
        headers={
            "Authorization": f"Bearer {os.environ['HF_TOKEN']}",
            "Content-Type": "application/json",
        },
        timeout=120,
    )
    response.raise_for_status()
    return torch.load(io.BytesIO(response.content), weights_only=True)


@dataclass
class AppConfig:
    instance_name: str = "Qwerty"
    class_name: str = "Golden Retriever"
    num_inference_steps: int = 28
    guidance_scale: float = 4.0
    height: int = 1024
    width: int = 1024


@app.cls(
    image=image,
    gpu="H100",
    volumes={MODEL_DIR: volume},
    secrets=[huggingface_secret],
    scaledown_window=300,
    timeout=600,
)
class Model:
    @modal.enter()
    def load_model(self):
        import torch
        from diffusers import Flux2Pipeline

        volume.reload()

        pipe = Flux2Pipeline.from_pretrained(
            MODEL_DIR,
            text_encoder=None,
            tokenizer=None,
            torch_dtype=torch.bfloat16,
        ).to("cuda")
        pipe.load_lora_weights(LORA_DIR)
        self.pipe = pipe

    @modal.method()
    def inference(self, text, config):
        import torch

        prompt_embeds = remote_text_encode(text).to("cuda", dtype=torch.bfloat16)
        return self.pipe(
            prompt_embeds=prompt_embeds,
            num_inference_steps=config.num_inference_steps,
            guidance_scale=config.guidance_scale,
            height=config.height,
            width=config.width,
        ).images[0]


@app.function(image=image, max_containers=1)
@modal.concurrent(max_inputs=100)
@modal.asgi_app()
def fastapi_app():
    import gradio as gr
    from fastapi import FastAPI
    from gradio.routes import mount_gradio_app

    web_app = FastAPI()

    config = AppConfig()
    instance_phrase = f"{config.instance_name} the {config.class_name}"

    example_prompts = [
        f"{instance_phrase}",
        f"a painting of {instance_phrase.title()} With A Pearl Earring, by Vermeer",
        f"oil painting of {instance_phrase} flying through space as an astronaut",
        f"a painting of {instance_phrase} in cyberpunk city. character design by cory loftis. volumetric light, detailed, rendered in octane",
        f"drawing of {instance_phrase} high quality, cartoon, path traced, by studio ghibli and don bluth",
    ]

    def go(text=""):
        if not text:
            text = example_prompts[0]
        return Model().inference.remote(text, config)

    description = """Describe what they are doing or how a particular artist or style would depict them. Be fantastical! Try the examples below for inspiration.

Generated by a FLUX.2 [dev] LoRA trained on Modal."""

    theme = gr.themes.Default(primary_hue="green", secondary_hue="emerald", neutral_hue="neutral")

    with gr.Blocks(theme=theme, title=f"Generate images of {config.instance_name} on Modal") as interface:
        gr.Markdown(f"# Generate images of {instance_phrase}.\n\n{description}")
        with gr.Row():
            inp = gr.Textbox(
                label="",
                placeholder=f"Describe the version of {instance_phrase} you'd like to see",
                lines=10,
            )
            out = gr.Image(height=512, width=512, label="", min_width=512, elem_id="output")
        with gr.Row():
            btn = gr.Button("Dream", variant="primary", scale=2)
            btn.click(fn=go, inputs=inp, outputs=out)
            gr.Button("⚡️ Powered by Modal", variant="secondary", link="https://modal.com")

        with gr.Column(variant="compact"):
            for ii, prompt in enumerate(example_prompts):
                btn = gr.Button(prompt, variant="secondary")
                btn.click(fn=lambda idx=ii: example_prompts[idx], outputs=inp)

    return mount_gradio_app(app=web_app, blocks=interface, path="/")
